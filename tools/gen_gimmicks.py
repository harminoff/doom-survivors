"""Generate src/zscript/gameplay/stages/StageGimmicks.zs (stage items and
trap plates) from tools/stage_gimmicks.py. Run: python tools/gen_gimmicks.py
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from tools.gen_stages import STAGES  # noqa: E402
from tools.stage_gimmicks import ITEMS, PLATES, PROPS, RANDOM_ITEMS, TILESET  # noqa: E402
import random  # noqa: E402


def catalog_ids() -> dict[str, int]:
    text = (ROOT / "src/zscript/gameplay/catalog/ItemCatalog.zs").read_text(encoding="utf-8")
    consts = dict((k, int(v)) for k, v in re.findall(r"const (ID_\w+) = (\d+);", text))
    body = text[text.index("static String DisplayName"):]
    return {name: consts[key] for key, name in re.findall(r'if \(id == (ID_\w+)\) return "([^"]+)";', body)}


def map_number(slug: str) -> int:
    for entry in STAGES:
        if entry[0] == slug:
            return int(entry[3][3:])
    raise KeyError(slug)


def blocked(spec: dict, x: float, y: float) -> bool:
    boxes = [p for p in spec.get("obstacles", [])] + [q["polygon"] for q in spec.get("patches", []) if q.get("blocking")]
    for poly in boxes:
        xs = [p[0] for p in poly]
        ys = [p[1] for p in poly]
        if min(xs) - 60 < x < max(xs) + 60 and min(ys) - 60 < y < max(ys) + 60:
            return True
    return False


def place(spec: dict, dx: float, dy: float) -> tuple[int, int]:
    xs = [p[0] for p in spec["room"]]
    ys = [p[1] for p in spec["room"]]
    x = spec["player"]["x"] + dx * TILESET
    y = spec["player"]["y"] + dy * TILESET
    x = min(max(x, min(xs) + 250), max(xs) - 250)
    y = min(max(y, min(ys) + 250), max(ys) - 250)
    for _ in range(14):
        if not blocked(spec, x, y):
            break
        x += 150
        y += 90
    return int(x), int(y)


def main() -> None:
    ids = catalog_ids()
    item_rows = []
    plate_rows = []
    for slug, rows in ITEMS.items():
        spec = json.loads((ROOT / f"maps/source/{slug}/room.json").read_text(encoding="utf-8"))
        for name, dx, dy, chance in rows:
            x, y = place(spec, dx, dy)
            item_rows.append((map_number(slug), ids[name], x, y, chance))
    for slug, names in RANDOM_ITEMS.items():
        spec = json.loads((ROOT / f"maps/source/{slug}/room.json").read_text(encoding="utf-8"))
        rng = random.Random(slug)
        xs = [p[0] for p in spec["room"]]
        ys = [p[1] for p in spec["room"]]
        for name in names:
            for _ in range(200):
                x = rng.randint(min(xs) + 300, max(xs) - 300)
                y = rng.randint(min(ys) + 300, max(ys) - 300)
                if not blocked(spec, x, y) and abs(x) + abs(y) > 600:
                    break
            item_rows.append((map_number(slug), ids[name], x, y, 100))
    for slug, rows in PLATES.items():
        for x, y, kind, tx, ty in rows:
            plate_rows.append((map_number(slug), x, y, kind, tx, ty))
    prop_rows = []
    for slug, rows in PROPS.items():
        for kind, x, y, tx, ty in rows:
            prop_rows.append((map_number(slug), kind, x, y, tx, ty))
    def arr(name, values):
        return f"    static const int {name}[] = {{ {', '.join(str(v) for v in values)} }};"
    lines = [
        "// GENERATED by tools/gen_gimmicks.py from tools/stage_gimmicks.py. Do not edit.",
        "// Stage items (wiki \"Stage items\") and trap plates, keyed by map number.",
        "class DSStageGimmicks",
        "{",
        arr("ITEM_MAP", [r[0] for r in item_rows]),
        arr("ITEM_ID", [r[1] for r in item_rows]),
        arr("ITEM_X", [r[2] for r in item_rows]),
        arr("ITEM_Y", [r[3] for r in item_rows]),
        arr("ITEM_CHANCE", [r[4] for r in item_rows]),
        arr("PLATE_MAP", [r[0] for r in plate_rows]),
        arr("PLATE_X", [r[1] for r in plate_rows]),
        arr("PLATE_Y", [r[2] for r in plate_rows]),
        arr("PLATE_KIND", [r[3] for r in plate_rows]),
        arr("PLATE_TX", [r[4] for r in plate_rows]),
        arr("PLATE_TY", [r[5] for r in plate_rows]),
        arr("PROP_MAP", [r[0] for r in prop_rows]),
        arr("PROP_KIND", [r[1] for r in prop_rows]),
        arr("PROP_X", [r[2] for r in prop_rows]),
        arr("PROP_Y", [r[3] for r in prop_rows]),
        arr("PROP_TX", [r[4] for r in prop_rows]),
        arr("PROP_TY", [r[5] for r in prop_rows]),
        f"    static int PropCount() {{ return {len(prop_rows)}; }}",
        f"    static int ItemCount() {{ return {len(item_rows)}; }}",
        f"    static int PlateCount() {{ return {len(plate_rows)}; }}",
        "}",
    ]
    (ROOT / "src/zscript/gameplay/stages/StageGimmicks.zs").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(item_rows)} stage items and {len(plate_rows)} plates")


if __name__ == "__main__":
    main()
