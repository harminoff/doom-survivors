"""Generate maps/source/mad-forest/room.json.

Approximates the source stage (wiki Tilemap-Mad_Forest, Mad_Forest_preview):
a large bounded field of dark mossy grass, a dirt-path cross with a side
branch, a few ponds, sparse dead trees, bushes, rocks, flower tufts and a
small graveyard. Nothing solid but the ponds; a distant treeline panorama
closes the horizon. Run: python tools/gen_mad_forest_room.py
"""
from __future__ import annotations

import json
import math
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HALF = 6144
EDGE = HALF - 64          # patches stay clear of the boundary wall

# Dirt paths as one rectilinear polygon (counter-clockwise): a north-south
# path at x -650..-510, an east-west path at y 630..770 ending at x 2000, and
# a branch at y -3070..-2930 ending at x 4000.
VX0, VX1 = -650, -510
HY0, HY1, XEND = 630, 770, 2000
BY0, BY1, BEND = -3070, -2930, 4000
PATH = [
    (VX0, -EDGE), (VX1, -EDGE), (VX1, BY0), (BEND, BY0), (BEND, BY1), (VX1, BY1),
    (VX1, HY0), (XEND, HY0), (XEND, HY1), (VX1, HY1), (VX1, EDGE), (VX0, EDGE),
    (VX0, HY1), (-EDGE, HY1), (-EDGE, HY0), (VX0, HY0),
]
PATH_RECTS = [(VX0, -EDGE, VX1, EDGE), (-EDGE, HY0, XEND, HY1), (VX1, BY0, BEND, BY1)]
PONDS = [(2600, 4300, 420, 280), (3900, 4000, 300, 220), (4700, 4700, 260, 200), (-3200, -4300, 380, 260)]
GRAVEYARD = (-4300, 3800)


def ellipse(cx, cy, rx, ry, n=14):
    return [(int(cx + rx * math.cos(2 * math.pi * i / n)), int(cy + ry * math.sin(2 * math.pi * i / n))) for i in range(n)]


def near_path(x, y, margin):
    return any(x0 - margin < x < x1 + margin and y0 - margin < y < y1 + margin for x0, y0, x1, y1 in PATH_RECTS)


def in_pond(x, y, margin):
    return any(((x - cx) / (rx + margin)) ** 2 + ((y - cy) / (ry + margin)) ** 2 < 1 for cx, cy, rx, ry in PONDS)


def decor(rng):
    props = []
    def scatter(count, types, margin, keep_start=250):
        placed = 0
        while placed < count:
            x = rng.randint(-HALF + 300, HALF - 300); y = rng.randint(-HALF + 300, HALF - 300)
            if math.hypot(x, y) < keep_start or near_path(x, y, margin) or in_pond(x, y, margin):
                continue
            props.append({"x": x, "y": y, "type": rng.choice(types)})
            placed += 1
    scatter(80, [30101, 30102, 30103], 60)
    scatter(170, [30104, 30105], 40)
    scatter(70, [30106, 30107], 40)
    scatter(140, [30108, 30109], 30, 120)
    # A treeline of dead trees just inside the boundary (the horizon).
    for i in range(-HALF + 100, HALF - 99, 110):
        for edge in (-1, 1):
            off = HALF - rng.randint(120, 330)
            props.append({"x": i + rng.randint(-30, 30), "y": edge * off, "type": rng.choice([30101, 30102, 30103])})
            props.append({"x": edge * off, "y": i + rng.randint(-30, 30), "type": rng.choice([30101, 30102, 30103])})
    gx, gy = GRAVEYARD
    for i in range(4):
        for j in range(3):
            props.append({"x": gx + i * 120, "y": gy - j * 130, "type": 30110})
    return props


def main():
    rng = random.Random(1603)
    spec = json.loads((ROOT / "maps/source/mad-forest/room.json").read_text(encoding="utf-8"))
    spec["obstacles"] = []
    spec["landmark"] = [[HALF - 200, HALF - 200], [HALF - 160, HALF - 200], [HALF - 160, HALF - 160], [HALF - 200, HALF - 160]]
    spec["patches"] = [{"floor": "path", "polygon": [list(p) for p in PATH]}] + [
        {"floor": "water", "blocking": True, "polygon": [list(p) for p in ellipse(*pond)]} for pond in PONDS]
    spec["decor"] = decor(rng)
    spec["notes"] = ["Approximation of the source Mad Forest layout (wiki tilemap): open dark-grass field, dirt-path "
                     "cross, ponds and sparse decor. Generated by tools/gen_mad_forest_room.py (seed 1603)."]
    (ROOT / "maps/source/mad-forest/room.json").write_text(json.dumps(spec, indent=1) + "\n", encoding="utf-8")
    print("wrote", len(spec["decor"]), "decor props")


if __name__ == "__main__":
    main()
