"""Generate src/zscript/gameplay/catalog/ItemText.zs (one short description per catalog
item, shown on the level-up cards) from data/ui/item-descriptions.json.
Run: python tools/gen_item_text.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "data/ui/item-descriptions.json"
OUT = ROOT / "src/zscript/gameplay/catalog/ItemText.zs"


def main() -> None:
    data = json.loads(SRC.read_text(encoding="utf-8"))
    rows = sorted((int(k), v) for k, v in data.items() if k.isdigit())
    ids = ", ".join(str(i) for i, _ in rows)
    texts = ", ".join('"' + v["text"].replace("\\", "").replace('"', "'") + '"' for _, v in rows)
    OUT.write_text(
        "// GENERATED by tools/gen_item_text.py from data/ui/item-descriptions.json. Do not edit.\n"
        "// One short description per catalog item for the level-up cards (own wording, wiki facts).\n"
        "class DSItemText\n{\n"
        f"    static const int IDS[] = {{ {ids} }};\n"
        f"    static const String TEXTS[] = {{ {texts} }};\n"
        "    static clearscope String Describe(int id)\n    {\n"
        "        for (int i = 0; i < DSItemText.IDS.Size(); i++)\n"
        "            if (DSItemText.IDS[i] == id) return DSItemText.TEXTS[i];\n"
        "        return \"\";\n    }\n}\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} items")


if __name__ == "__main__":
    main()
