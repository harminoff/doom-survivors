"""Final mix of the sound effects: raw review takes -> game files + SNDINFO + ZScript table.

Reads tools/audio/sound_table.py (every sound, its role and settings) and the picked take of
each from the review folder (tools/audio/sa3_sfx.py), and writes
  src/resources/sounds/<group>/<key>.ogg     the game files (Vorbis, small in git)
  src/resources/SNDINFO                       logical names, pitch variation, voice limits
  src/zscript/gameplay/slice/SliceAudioTable.zs   the DSSfx enum and lookup tables

How games keep music and effects from fighting (and what is done here):
  1. Roles and a loudness ladder. Music is the bed (about -28 LUFS integrated); weapon fire,
     hits, deaths and pickups (several per second) sit AT OR BELOW the music so a crowd of
     them cannot pile up; feedback the player must notice (level up, chest, being hurt) sits
     a few LU above; stingers (boss, evolution, victory) are the loudest, and the music is
     ducked underneath them (DSSfx.DUCK / HOLD, applied in SliceAudio.zs).
  2. Frequency separation. Music owns the low mids (200-800 Hz). Effects are high-passed
     (frequent ones hard, so no thump over the bass), get a cut where the music's body lives
     and a lift in the presence band (2-5 kHz) so they cut through without being louder.
     Only stingers keep low end.
  3. Variation. Frequent sounds get a small random pitch range (SNDINFO $pitchset) and a
     simultaneous-voice limit ($limit) so repeats do not machine-gun; the effects bus gain
     (SliceAudio.zs BusGain) lowers crowds of them.
  4. Headroom. Every file is peak-limited, so the sum of music and effects does not clip.
Each effect's loudness is its own event loudness (BS.1770 K-weighted over the sound).
Run (needs only numpy/scipy/soundfile):  python tools/audio/sfx_mix.py [KEY ...]
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import soundfile as sf

sys.path.insert(0, str(Path(__file__).resolve().parent))
from paths import REVIEW_ROOT   # noqa: E402
import mixer   # noqa: E402
import sound_table as table   # noqa: E402
from sound_table import CATEGORIES, ROLES, SOUNDS, file_stem, logical, setting   # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
SOUNDS_DIR = ROOT / "src/resources/sounds"
SNDINFO = ROOT / "src/resources/SNDINFO"
ZTABLE = ROOT / "src/zscript/gameplay/slice/SliceAudioTable.zs"
REVIEW = REVIEW_ROOT / "sfx3m"
RATE = 44100
FREQUENT = table.COMBAT


def game_path(key: str) -> Path:
    return SOUNDS_DIR / SOUNDS[key].group / f"{file_stem(key)}.ogg"


def write_ogg(path: Path, audio: np.ndarray) -> None:
    # same as music_master.write_ogg: libsndfile's Vorbis encoder wants 16-bit data in blocks
    pcm = np.clip(audio * 32767.0, -32768, 32767).astype(np.int16).reshape(-1, 1)
    with sf.SoundFile(path, "w", samplerate=RATE, channels=1, format="OGG", subtype="VORBIS") as f:
        for start in range(0, len(pcm), 4096):
            f.write(pcm[start: start + 4096])


def process(key: str, raw: np.ndarray) -> np.ndarray:
    role = SOUNDS[key].role
    r = ROLES[role]
    x = raw.astype(np.float32)
    if r["max_len"] and len(x) > r["max_len"] * RATE:
        # frequent sounds keep only their head: long tails of many overlapping sounds
        # are what turns a crowd into a wash
        n = int(r["max_len"] * RATE)
        fade = min(n // 3, int(0.06 * RATE))
        x = x[:n].copy()
        x[-fade:] *= np.linspace(1.0, 0.0, fade, dtype=np.float32)
    x = mixer.highpass(x, RATE, r["hp"], order=4 if role in FREQUENT + ("ui",) else 2)
    if r["body"]:
        x = mixer.apply(x, "peak", RATE, 450.0, 0.9, r["body"])
    if r["presence"]:
        x = mixer.apply(x, "peak", RATE, 3000.0, 0.8, r["presence"])
    # level to the target event loudness, then limit (limiting lowers loudness slightly, so
    # re-measure and nudge once)
    target = setting(key, "lufs")
    for _ in range(2):
        gain = mixer.from_db(target - mixer.event_lufs(x, RATE))
        x = mixer.limit(x * gain, RATE, ceiling_db=r["ceiling"], lookahead_ms=2.0, release_ms=40.0)
    return x


def build_sndinfo() -> str:
    lines = ["// GENERATED by tools/audio/sfx_mix.py from tools/audio/sound_table.py. Do not edit.",
             "// Loudness lives in the files; the lines below only name the sounds and add",
             "// pitch variation and voice limits.", ""]
    for key in SOUNDS:
        lines.append(f"{logical(key)} \"sounds/{SOUNDS[key].group}/{file_stem(key)}.ogg\"")
    lines.append("")
    for alias, key in table.MENU_ALIASES.items():
        lines.append(f"{alias} \"sounds/{SOUNDS[key].group}/{file_stem(key)}.ogg\"")
    lines.append("")
    for key in SOUNDS:
        pitch, limit = setting(key, "pitch"), setting(key, "limit")
        if pitch:
            lines.append(f"$pitchset {logical(key)} {pitch[0]} {pitch[1]}")
        if limit:
            lines.append(f"$limit {logical(key)} {limit}")
    return "\n".join(lines) + "\n"


def build_ztable() -> str:
    keys = list(SOUNDS)

    def rows(values, per=8):
        return ",\n".join("        " + ", ".join(values[i:i + per]) for i in range(0, len(values), per))

    weapon = "\n".join(f"            case {system}: return {key};" for system, key in table.WEAPON.items())
    hits = "\n".join(f"        if (engine == \"{name}\") return {key};" for name, key in table.HIT.items())
    return f"""// GENERATED by tools/audio/sfx_mix.py from tools/audio/sound_table.py. Do not edit.
// Every sound effect (DSSfx enum), its logical SNDINFO name, how much it ducks the music
// and for how long, whether it is on the effects bus, and the game-id -> sound lookups.
// Presentation only: playing a sound never changes game state.

class DSSfx
{{
    enum ESfx
    {{
{rows(keys)},
        SFX_COUNT
    }}

    static const String NAMES[] = {{
{rows([f'"{logical(k)}"' for k in keys], 4)}
    }};
    // music gain while the sound plays (1.0 = no ducking) and how long it is held (tics)
    static const double DUCK[] = {{
{rows([f"{setting(k, 'duck'):g}" for k in keys], 16)}
    }};
    static const int HOLD[] = {{
{rows([str(setting(k, 'hold')) for k in keys], 16)}
    }};
    // category of each sound ({", ".join(f"{i} {c}" for i, c in enumerate(CATEGORIES))});
    // the first {len(FREQUENT)} are the combat bus (rate-limited and ducked, SliceAudio.zs)
    static const int CAT[] = {{
{rows([str(CATEGORIES.index(SOUNDS[k].role)) for k in keys], 32)}
    }};
    const CAT_COUNT = {len(CATEGORIES)};
    const COMBAT_CATS = {len(FREQUENT)};
{chr(10).join(f"    const CAT_{c.upper()} = {i};" for i, c in enumerate(CATEGORIES))}
    const DUCK_RELEASE = 25;

    // fire sound of a weapon system (SYSTEM_* ids)
    static int ForWeapon(int system)
    {{
        switch (system)
        {{
{weapon}
        }}
        return SHOOT;
    }}

    // hit sound of a weapon engine (N2CreditDamage engine names)
    static int ForHitEngine(String engine)
    {{
{hits}
        return HIT;
    }}

    // death sound of an enemy family (DSStage.Family)
    static const int FAMILY_SFX[] = {{ {", ".join(str(keys.index(k)) for k in table.FAMILY)} }};   // {" ".join(table.FAMILY)}
    const FAMILY_SFX_COUNT = {len(table.FAMILY)};
    static int ForFamily(int family)
    {{
        return family > 0 && family < FAMILY_SFX_COUNT ? DSSfx.FAMILY_SFX[family] : DEATH;
    }}

    // pickup sound of a stage item (MF_ITEM_* kinds)
    static const int ITEM_SFX[] = {{ {", ".join(str(keys.index(k)) for k in table.ITEM)} }};   // {" ".join(table.ITEM)}
    const ITEM_SFX_COUNT = {len(table.ITEM)};
    static int ForItem(int kind)
    {{
        return kind > 0 && kind < ITEM_SFX_COUNT ? DSSfx.ITEM_SFX[kind] : COIN;
    }}
}}
"""


def main() -> None:
    keys = sys.argv[1:] or list(SOUNDS)
    missing = []
    for key in keys:
        folder = REVIEW / key
        picked = int((folder / "picked.txt").read_text().strip() or 1) if (folder / "picked.txt").exists() else 1
        take = folder / f"take{picked}.wav"
        if not take.exists():
            missing.append(key)
            continue
        raw, rate = sf.read(take)
        assert rate == RATE, rate
        if raw.ndim == 2:
            raw = raw.mean(axis=1)
        out = process(key, raw)
        path = game_path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        write_ogg(path, out)
        print(f"{key:22s} take{picked} {SOUNDS[key].role:9s} {mixer.event_lufs(out, RATE):6.1f} LUFS  "
              f"peak {mixer.peak_db(out):5.1f} dB  {len(out) / RATE:.2f}s")
    SNDINFO.write_text(build_sndinfo(), encoding="utf-8")
    ZTABLE.write_text(build_ztable(), encoding="utf-8")
    print(f"wrote SNDINFO and {ZTABLE.name}")
    if missing:
        print(f"MISSING takes (generate with sa3_sfx.py): {' '.join(missing)}")
        sys.exit(1)


if __name__ == "__main__":
    main()
