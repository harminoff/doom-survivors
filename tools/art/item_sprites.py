"""Copy each HUD item icon (graphics/HI<id>.png) to a world sprite I<id>A0
(centre origin) and write the ZScript state registry that lets
Actor.GetSpriteIndex find them. Run after item_icons.py:
python tools/art/item_sprites.py
"""
from __future__ import annotations

import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
from pickup_art import add_grab  # noqa: E402


def main() -> None:
    ids = []
    for icon in sorted((ROOT / "src/resources/graphics").glob("HI*.png")):
        item_id = int(icon.stem[2:])
        target = ROOT / f"src/resources/sprites/I{item_id:03d}A0.png"
        shutil.copyfile(icon, target)
        from PIL import Image
        w, h = Image.open(target).size
        add_grab(target, w // 2, h // 2)
        ids.append(item_id)
    lines = ["// GENERATED by tools/art/item_sprites.py. Do not edit.",
             "// Never spawned: its states register the stage-item sprite names.",
             "class DSItemSpriteRegistry : Actor", "{", "    States", "    {", "    Spawn:"]
    lines += [f"        I{i:03d} A 1;" for i in ids]
    lines += ["        Stop;", "    }", "}"]
    (ROOT / "src/zscript/gameplay/presentation/ItemSprites.zs").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(ids)} item sprites")


if __name__ == "__main__":
    main()
