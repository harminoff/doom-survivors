"""Generate src/zscript/gameplay/meta/RecipeBook.zs: every evolution and union
recipe (output, weapon, passive) read from TransformationGraph.zs, for the
Grim Grimoire's recipe view in the Collection.
Run: python tools/gen_recipes.py
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GRAPH = ROOT / "src/zscript/gameplay/transformations/TransformationGraph.zs"
OUT = ROOT / "src/zscript/gameplay/meta/RecipeBook.zs"


def body(text: str, name: str) -> str:
    start = text.index(f"int {name}(int recipeId)")
    depth = 0
    for i in range(text.index("{", start), len(text)):
        depth += {"{": 1, "}": -1}.get(text[i], 0)
        if depth == 0:
            return text[start:i]
    raise ValueError(name)


def main() -> None:
    text = GRAPH.read_text(encoding="utf-8")
    consts = {k: int(v) for k, v in re.findall(r"const (DSP032_\w+) = (\d+);", text)}

    def table(name: str) -> dict[int, int]:
        out = {}
        for recipe, value in re.findall(r"if \(recipeId == (DSP032_RECIPE_\w+)\) return (DSP032_ID_\w+);", body(text, name)):
            out[consts[recipe]] = consts[value]
        return out

    a, b, o = table("DSP032RecipeInputA"), table("DSP032RecipeInputB"), table("DSP032RecipeOutput")
    second = table("DSP032RecipeSecondPassive")
    rows = sorted((r, o[r], a[r], b.get(r, 0), second.get(r, 0)) for r in o if r in a and r < 1000)
    col = lambda i: ", ".join(str(row[i]) for row in rows)  # noqa: E731
    OUT.write_text(f"""// GENERATED by tools/gen_recipes.py from TransformationGraph.zs. Do not edit.
// Evolution and union recipes for the Grim Grimoire (output, weapon, partner,
// second passive).
class DSRecipeBook
{{
    static const int OUTPUT[] = {{ {col(1)} }};
    static const int INPUT_A[] = {{ {col(2)} }};
    static const int INPUT_B[] = {{ {col(3)} }};
    static const int SECOND[] = {{ {col(4)} }};

    // "Weapon + Passive" for an evolution, or "" if it is none.
    static clearscope String Recipe(int output)
    {{
        for (int i = 0; i < DSRecipeBook.OUTPUT.Size(); i++)
        {{
            if (DSRecipeBook.OUTPUT[i] != output) continue;
            String text = DSN2Catalog.DisplayName(DSRecipeBook.INPUT_A[i]);
            if (DSRecipeBook.INPUT_B[i] > 0) text = text .. " + " .. DSN2Catalog.DisplayName(DSRecipeBook.INPUT_B[i]);
            if (DSRecipeBook.SECOND[i] > 0) text = text .. " + " .. DSN2Catalog.DisplayName(DSRecipeBook.SECOND[i]);
            return text;
        }}
        return "";
    }}

    // What a weapon or passive helps make: the first evolution using it.
    static clearscope int UsedIn(int id)
    {{
        for (int i = 0; i < DSRecipeBook.OUTPUT.Size(); i++)
            if (DSRecipeBook.INPUT_A[i] == id || DSRecipeBook.INPUT_B[i] == id || DSRecipeBook.SECOND[i] == id)
                return DSRecipeBook.OUTPUT[i];
        return 0;
    }}
}}
""", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} recipes")


if __name__ == "__main__":
    main()
